package example;
import org.bytedeco.pytorch.nn.*;
import org.bytedeco.pytorch.nn.modules.*;
import org.bytedeco.pytorch.nn.modules.container.*;

import org.bytedeco.javacpp.Loader;
import org.bytedeco.javacpp.PointerScope;
import org.bytedeco.pytorch.Tensor;
import org.bytedeco.pytorch.global.torch;
import org.bytedeco.pytorch.nn.Module;
import org.bytedeco.pytorch.nn.modules.DropoutImpl;
import org.bytedeco.pytorch.nn.modules.LinearImpl;
import org.bytedeco.pytorch.nn.modules.ReLUImpl;
import org.bytedeco.pytorch.nn.modules.container.SequentialImpl;

/**
 * Benchmarks the generic
 * {@link SequentialImpl#push_back(Module)
 * SequentialImpl.push_back(Module)} overload and the corresponding
 * {@code push_back(String, Module)} variant against the typed
 * {@code push_back(LinearImpl)} family.
 *
 * <p>The generic overload is generated by JavaCPP from a C++ helper
 * ({@code torch::nn::push_back_module}) that does
 * {@code dynamic_cast} on the actual C++ typeid and forwards to the
 * matching typed {@code push_back<Impl>} overload. As a result the
 * per-call cost on the JNI side is one extra C++-side cast compared
 * with the typed path, while the Java side has a single virtual-style
 * method call instead of a reflective one.
 *
 * <p>Three model architectures are exercised:
 * <ol>
 *   <li>A <strong>MLP</strong> built from {@link LinearImpl} layers.</li>
 *   <li>A <strong>ResNet-like</strong> deep stack of
 *       {@link LinearImpl}/{@link ReLUImpl}/{@link DropoutImpl} layers.</li>
 *   <li>A <strong>DeepFM</strong> hybrid with linear and dropout sub-modules.</li>
 * </ol>
 */
public class BenchmarkSequentialPushBackModule {

    // -----------------------------------------------------------------------
    // Custom user-defined module — exercises the untyped reflection path.
    // -----------------------------------------------------------------------

    /** User-defined module that wraps a single {@link LinearImpl}. */
    public static final class CustomMLP extends Module {
        public CustomMLP(long in, long out) {
            super("CustomMLP");
            register_module("fc", new LinearImpl(in, out));
        }

        public CustomMLP(org.bytedeco.javacpp.Pointer p) {
            super(p);
        }
    }

    // -----------------------------------------------------------------------
    // Benchmarks.
    // -----------------------------------------------------------------------

    private static final int ITERATIONS = 5_0;
    private static final int WARMUP = 10;

    /** Build a fresh MLP and forward through it; uses the typed push_back. */
    private static double benchTypedPushBack() {
        long start = System.nanoTime();
        for (int i = 0; i < ITERATIONS; i++) {
            try (PointerScope scope = new PointerScope()) {
                SequentialImpl seq = new SequentialImpl();
                seq.push_back(new LinearImpl(64L, 128L));
                seq.push_back(new ReLUImpl());
                seq.push_back(new LinearImpl(128L, 64L));
                seq.push_back(new ReLUImpl());
                seq.push_back(new LinearImpl(64L, 10L));
                Tensor y = seq.forward(torch.randn(new long[]{4, 64}));
                if (y.sizes().get(1) != 10) {
                    throw new AssertionError();
                }
            }
        }
        return (System.nanoTime() - start) / 1_000.0 / ITERATIONS;
    }

    /** Build a fresh MLP using the generic push_back(Module) path. */
    private static double benchGenericPushBack() {
        long start = System.nanoTime();
        for (int i = 0; i < ITERATIONS; i++) {
            try (PointerScope scope = new PointerScope()) {
                SequentialImpl seq = new SequentialImpl();
                LinearImpl m1 = new LinearImpl(64L, 128L);
                ReLUImpl m2 = new ReLUImpl();
                LinearImpl m3 = new LinearImpl(128L, 64L);
                ReLUImpl m4 = new ReLUImpl();
                LinearImpl m5 = new LinearImpl(64L, 10L);
                seq.push_back(m1);
                seq.push_back(m2);
                seq.push_back(m3);
                seq.push_back(m4);
                seq.push_back(m5);
                Tensor y = seq.forward(torch.randn(new long[]{4, 64}));
                if (y.sizes().get(1) != 10) {
                    throw new AssertionError();
                }
            }
        }
        return (System.nanoTime() - start) / 1_000.0 / ITERATIONS;
    }

    /** Build a fresh ResNet-like stack — exercises a longer sequential. */
    private static double benchGenericResNet() {
        long start = System.nanoTime();
        for (int i = 0; i < ITERATIONS; i++) {
            try (PointerScope scope = new PointerScope()) {
                SequentialImpl seq = new SequentialImpl();
                Module[] layers = new Module[]{
                    new LinearImpl(192L, 256L),
                    new ReLUImpl(),
                    new DropoutImpl(0.1),
                    new LinearImpl(256L, 256L),
                    new ReLUImpl(),
                    new DropoutImpl(0.1),
                    new LinearImpl(256L, 128L),
                    new ReLUImpl(),
                    new LinearImpl(128L, 10L),
                };
                for (Module m : layers) {
                    seq.push_back(m);
                }
                Tensor y = seq.forward(torch.randn(new long[]{2, 192}));
                if (y.sizes().get(1) != 10) {
                    throw new AssertionError();
                }
            }
        }
        return (System.nanoTime() - start) / 1_000.0 / ITERATIONS;
    }

    /** Build a DeepFM-style hybrid module. */
    private static double benchGenericDeepFM() {
        long start = System.nanoTime();
        for (int i = 0; i < ITERATIONS; i++) {
            try (PointerScope scope = new PointerScope()) {
                SequentialImpl seq = new SequentialImpl();
                LinearImpl m1 = new LinearImpl(64L, 1L);
                LinearImpl m2 = new LinearImpl(64L, 128L);
                ReLUImpl m3 = new ReLUImpl();
                DropoutImpl m4 = new DropoutImpl(0.2);
                LinearImpl m5 = new LinearImpl(128L, 1L);
                seq.push_back("linear_w", m1);
                seq.push_back("fc1",      m2);
                seq.push_back("relu1",    m3);
                seq.push_back("dropout1", m4);
                seq.push_back("fc2",      m5);
                if (seq.size() != 5) {
                    throw new AssertionError();
                }
            }
        }
        return (System.nanoTime() - start) / 1_000.0 / ITERATIONS;
    }

    // -----------------------------------------------------------------------
    // Functional verification.
    // -----------------------------------------------------------------------

    private static void verifyForward() {
        try (PointerScope scope = new PointerScope()) {
            SequentialImpl seq = new SequentialImpl();
            LinearImpl m1 = new LinearImpl(8L, 16L);
            ReLUImpl m2 = new ReLUImpl();
            LinearImpl m3 = new LinearImpl(16L, 4L);
            seq.push_back(m1);
            seq.push_back(m2);
            seq.push_back(new DropoutImpl(0.2));
            seq.push_back(m3);
            check(seq.size() == 4, "sequential should have 3 modules via generic push_back");

            Tensor y = seq.forward(torch.randn(new long[]{2, 8}));
            check(y.dim() == 2, "forward output should be rank-2");
            check(y.sizes().get(0) == 2, "batch");
            check(y.sizes().get(1) == 4, "features");
            System.out.println("[verify] generic push_back forward sum = " + y.sum().item_double());
        }
    }

    private static void verifyNamedPushBack() {
        try (PointerScope scope = new PointerScope()) {
            SequentialImpl seq = new SequentialImpl();
            LinearImpl m1 = new LinearImpl(4L, 4L);
            ReLUImpl m2 = new ReLUImpl();
            seq.push_back("first",  m1);
            seq.push_back("second", m2);
            check(seq.size() == 2, "named push_back should produce 2 modules");
            System.out.println("[verify] named push_back OK, size = " + seq.size());
        }
    }

    private static void check(boolean cond, String msg) {
        if (!cond) {
            throw new AssertionError(msg);
        }
    }

    // -----------------------------------------------------------------------
    // Reporting.
    // -----------------------------------------------------------------------

    private static void runBenchmarks() {
        // warm up
        for (int i = 0; i < WARMUP; i++) {
            benchTypedPushBack();
            benchGenericPushBack();
            benchGenericResNet();
            benchGenericDeepFM();
        }

        double typed   = benchTypedPushBack();
        double generic = benchGenericPushBack();
        double resnet  = benchGenericResNet();
        double deepfm  = benchGenericDeepFM();

        System.out.println();
        System.out.println("==== BenchmarkSequentialPushBackModule ====");
        System.out.printf("iterations              = %,d (after %,d warmup)%n", ITERATIONS, WARMUP);
        System.out.printf("typed push_back(Impl)   = %.3f us / build+forward%n", typed);
        System.out.printf("generic push_back(Mod)  = %.3f us / build+forward  (overhead = %.3f us)%n",
                generic, generic - typed);
        System.out.printf("generic push_back x9    = %.3f us / ResNet build%n", resnet);
        System.out.printf("generic push_back x5    = %.3f us / DeepFM build (named)%n", deepfm);
        System.out.println();
        System.out.println("Lower is better. Generic path should be within 2x of typed.");
    }

    public static void main(String[] args) {
        Loader.load(torch.class);
        verifyForward();
        verifyNamedPushBack();
        runBenchmarks();
    }
}